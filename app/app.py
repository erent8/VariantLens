AA_ORDER = "DEKRHNQSTYCGAVLIMPFW"  # grouped by physico-chemistry for the heatmap
ORDER_IDX = [AA_IDX[a] for a in AA_ORDER]


# ----------------------------------------------------------------- data
@st.cache_data
def load():
    v = pd.read_parquet(DATA / "variants.parquet")
    p = pd.read_parquet(DATA / "proteins.parquet").sort_values("n", ascending=False)
    cal = json.loads((DATA / "calibration.json").read_text())
    metrics = json.loads((ROOT / "results/metrics.json").read_text()) if (ROOT / "results/metrics.json").exists() else None
    return v, p, cal, metrics


@st.cache_data
def am_for(acc: str) -> pd.DataFrame:
    f = DATA / "am_landscape.parquet"  # large, regenerated by scripts/05_build_app_data.py
    if not f.exists():
        return pd.DataFrame({"uniprot": [], "variant": [], "am_pathogenicity": []})
    return pd.read_parquet(f, filters=[("uniprot", "==", acc)])


@st.cache_data
def landscape(acc: str) -> np.ndarray | None:
    for d in (DATA / "landscapes", ROOT / "data/processed/landscapes/esm2_650M"):
        if (d / f"{acc}.npy").exists():
            return np.load(d / f"{acc}.npy").astype(np.float32)
    return None


@st.cache_data(show_spinner=False)
def alphafold_pdb(acc: str) -> str | None:
    try:
        meta = requests.get(f"https://alphafold.ebi.ac.uk/api/prediction/{acc}", timeout=20).json()
        return requests.get(meta[0]["pdbUrl"], timeout=30).text
    except Exception:
        return None


def to_matrix(seq: str, variants: list[str], values) -> np.ndarray:
    M = np.full((len(seq), 20), np.nan, np.float32)
    for v, x in zip(variants, values):
        M[int(v[1:-1]) - 1, AA_IDX[v[-1]]] = x
    return M


@st.cache_data(show_spinner="Running VariantLens on every substitution …")
def vl_matrices(acc: str, seq: str) -> dict[str, np.ndarray]:
    L = landscape(acc)
    am = am_for(acc)
    vs = vlp.all_variants(seq)
    pr = vlp.predict(L, seq, vs, dict(zip(am.variant, am.am_pathogenicity)))
    return {k: to_matrix(seq, vs, p) for k, p in pr.items()}


@st.cache_resource(show_spinner="Loading ESM-2 …")
def scorer(name: str):
    from variantlens.esm_scoring import ESMScorer
    return ESMScorer(name)


def p_path(llr, cal):
    return 1 / (1 + np.exp(-(cal["coef"] * llr + cal["intercept"])))


def am_tag(x, cal):
    lo, hi = cal["am_thresholds"]
    return ("likely pathogenic", "path") if x > hi else ("likely benign", "ben") if x < lo else ("ambiguous", "amb")


def card(title, big, tag=None, cls="", sub=""):
    t = f'<span class="vl-tag {cls}">{tag}</span>' if tag else ""
    return f'<div class="vl-card"><h4>{title}</h4><div class="vl-big">{big}</div>{t}<div style="opacity:.7;font-size:.85rem;margin-top:6px">{sub}</div></div>'


