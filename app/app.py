PROB_SCALE = [[0, "#2166ac"], [0.3, "#92c5de"], [0.5, "#f7f7f7"], [0.75, "#f4a582"], [1, "#8c1c13"]]


def heatmap(L: np.ndarray, seq: str, clin: pd.DataFrame | None = None, am: pd.DataFrame | None = None,
            title="", P: np.ndarray | None = None, p_name: str = ""):
    """Landscape heatmap coloured by ESM LLR, or by a probability matrix P (L x 20)."""
    n = len(seq)
    llrZ = L[:, ORDER_IDX].T
    Z = llrZ if P is None else P[:, ORDER_IDX].T
    amZ = np.full((20, n), np.nan)
    if am is not None and len(am):
        for var, s in zip(am.variant, am.am_pathogenicity):
            p = int(var[1:-1]) - 1
            if p < n:
                amZ[AA_ORDER.index(var[-1]), p] = s
    custom = np.dstack([amZ, np.tile(np.array(list(seq))[None, :], (20, 1)), llrZ])
    hover = "<b>%{customdata[1]}%{x}%{y}</b><br>ESM LLR: %{customdata[2]:.2f}<br>AlphaMissense: %{customdata[0]:.3f}"
    if P is None:
        style = dict(colorscale=[[0, "#8c1c13"], [0.55, "#f4a582"], [0.8, "#f7f7f7"], [1, "#4393c3"]],
                     zmin=-14, zmax=2.5, colorbar=dict(title="ESM LLR", thickness=12, len=.8))
    else:
        style = dict(colorscale=PROB_SCALE, zmin=0, zmax=1, colorbar=dict(title="P(path.)", thickness=12, len=.8))
        hover += f"<br>{p_name}: %{{z:.2f}}"
    fig = go.Figure(go.Heatmap(z=Z, x=np.arange(1, n + 1), y=list(AA_ORDER), customdata=custom,
                               hovertemplate=hover + "<extra></extra>", **style))
    if clin is not None and len(clin):
        for lab, sym, col, name in [(1, "x", "#111", "ClinVar P/LP"), (0, "circle-open", "#1b7f4b", "ClinVar B/LB")]:
            c = clin[clin.label == lab]
            fig.add_trace(go.Scatter(
                x=[int(v[1:-1]) for v in c.variant], y=[v[-1] for v in c.variant], mode="markers", name=name,
                marker=dict(symbol=sym, size=7, color=col, line=dict(width=1.5, color=col)),
                text=c.variant + " · " + c.ClinicalSignificance, hovertemplate="%{text}<extra></extra>"))
    fig.update_layout(height=430, margin=dict(l=10, r=10, t=40, b=10), title=title,
                      xaxis=dict(title="residue", rangeslider=dict(visible=n > 400, thickness=.06)),
                      yaxis=dict(autorange="reversed", tickfont=dict(family="monospace")),
                      legend=dict(orientation="h", y=1.08, x=1, xanchor="right"))
    if n > 400:
        fig.update_xaxes(range=[0.5, 400.5])
    return fig


def track(L: np.ndarray, am: pd.DataFrame | None):
    sens = -np.nanmean(L, axis=1)
    fig = go.Figure(go.Scatter(x=np.arange(1, len(sens) + 1), y=sens, mode="lines", name="ESM-2 sensitivity",
                               line=dict(color="#e07a5f", width=1.4), fill="tozeroy", fillcolor="rgba(224,122,95,.15)"))
    if am is not None and len(am):
        a = am.assign(p=am.variant.str[1:-1].astype(int)).groupby("p").am_pathogenicity.mean()
        fig.add_trace(go.Scatter(x=a.index, y=a.values * sens.max(), mode="lines", name="AlphaMissense (scaled)",
                                 line=dict(color="#2a6f97", width=1.2), opacity=.8))
    fig.update_layout(height=220, margin=dict(l=10, r=10, t=10, b=10), xaxis_title="residue",
                      yaxis_title="mean −LLR", legend=dict(orientation="h", y=1.15, x=1, xanchor="right"))
    return fig


def structure_html(pdb: str, sens: np.ndarray, highlight: int | None):
    import py3Dmol
    lo, hi = np.percentile(sens, 5), np.percentile(sens, 95)
    lines = []
    for ln in pdb.splitlines():  # write sensitivity into the B-factor column
        if ln.startswith("ATOM"):
            r = int(ln[22:26]) - 1
            b = (sens[r] - lo) / (hi - lo + 1e-9) * 100 if r < len(sens) else 0
            ln = ln[:60] + f"{np.clip(b, 0, 100):6.2f}" + ln[66:]
        lines.append(ln)
    view = py3Dmol.view(width=620, height=460)
    view.addModel("\n".join(lines), "pdb")
    view.setStyle({"cartoon": {"colorscheme": {"prop": "b", "gradient": "rwb", "min": 100, "max": 0}}})
    if highlight is not None:
        sel = {"resi": highlight + 1}
        view.addStyle(sel, {"stick": {"colorscheme": "yellowCarbon", "radius": .3}})
        view.addStyle(sel, {"sphere": {"color": "yellow", "opacity": .55, "radius": 1.4}})
    view.zoomTo()
    view.setBackgroundColor("#0e1117")
    view.spin(False)
    return view._make_html()


